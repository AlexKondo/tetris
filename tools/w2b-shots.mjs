import { chromium } from 'playwright';
const b = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const p = await b.newPage({ viewport: { width: 430, height: 900 }, deviceScaleFactor: 1 });
const logs = [];
p.on('console', m => m.type() !== 'debug' && logs.push(m.type() + ': ' + m.text()));
p.on('pageerror', e => logs.push('PAGEERROR: ' + e.message));
await p.goto('http://localhost:5173/?seed=123&gravity=0');
await p.waitForFunction(() => window.__game && window.__game.logic);
const st = () => p.evaluate(() => { const l = window.__game.logic; return { piece: l.piece && { n: l.piece.name, col: l.piece.col, row: l.piece.row, rot: l.piece.rot }, score: l.score, rings: l.rings, rotY: +window.__game.tower.group.rotation.y.toFixed(3) }; });
const shot = async (n) => { await p.evaluate(() => window.__game.snapCamera()); await p.waitForTimeout(2500); await p.screenshot({ path: `screenshots/${n}.png`, timeout: 120000 }); };
console.log('initial', JSON.stringify(await st()));
await shot('w2b-initial');
for (let i = 0; i < 12; i++) await p.keyboard.press('ArrowRight');
console.log('after right x12', JSON.stringify(await st()));
await shot('w2b-right12');
const info = await p.evaluate(() => { const l = window.__game.logic; const top = l.rows - 7; let h = -1; for (let c = 0; c < l.cols; c++) if (!l.grid[(top) * l.cols + c]) { h = c; break; } return { top, h }; });
const hc = await p.evaluate(() => { const l = window.__game.logic; const r = l.rows - 14; for (let c = 0; c < l.cols; c++) if (!l.grid[r * l.cols + c]) return c; });
console.log('hole col', hc);
await p.evaluate((hc) => { const l = window.__game.logic; l.piece = { name: 'I', id: 1, col: hc, row: l.rows, rot: 1 }; }, hc);
await shot('w2b-before-clear');
await p.keyboard.press('Space');
console.log('after drop', JSON.stringify(await st()));
await shot('w2b-after-clear');
console.log(logs.join('\n') || 'no console errors');
await b.close();
